import json, os
H = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(H, "paths.json")))
ys = [14, 26, 38, 50, 62, 74, 86]
bars = d["bars"]
geo = "".join(d["geoscan"]); three = "".join(d["three"])
W = d["width"]
rows = []
for i, (y, x1, x2, role) in enumerate(bars):
    rows.append(f'  {{ y: {y}, x1: {x1:.2f}, x2: {x2:.2f}, beam: {str(role=="beam").lower()}, tone: {ys.index(y)} }},')
src = f'''/* Generated by _src/logo/emit_tsx.py from Switzer Semibold. Do not edit the path data by hand. */
import type {{ CSSProperties }} from "react";

/** The mark: a "G" drawn from seven LiDAR scan lines, shaded like a sphere, the laser as its crossbar. */
const BARS = [
{chr(10).join(rows)}
];
const SW = {d["sw"]};
const GEOSCAN = "{geo}";
const THREE = "{three}";
const WORD_W = {W:.2f};

type Tone = "light" | "dark";

export function Mark({{ tone = "light", className, title }}: {{ tone?: Tone; className?: string; title?: string }}) {{
  return (
    <svg viewBox="0 0 106 100" className={{`mark mark-${{tone}} ${{className ?? ""}}`}} role={{title ? "img" : undefined}} aria-hidden={{title ? undefined : true}} aria-label={{title}}>
      {{BARS.map((b, i) => (
        <line
          key={{i}}
          x1={{b.x1}} y1={{b.y}} x2={{b.x2}} y2={{b.y}}
          strokeWidth={{SW}} strokeLinecap="round"
          className={{b.beam ? "mark-beam" : `mark-bar t${{b.tone}}`}}
          style={{{{ "--i": i }} as CSSProperties}}
        />
      ))}}
    </svg>
  );
}}

/** Wordmark "Geoscan3D", outlined so it renders identically at any size. */
export function Wordmark({{ className }}: {{ className?: string }}) {{
  return (
    <svg viewBox={{`-2 -50 ${{WORD_W + 4}} 66`}} className={{`wordmark ${{className ?? ""}}`}} aria-hidden="true">
      <path d={{GEOSCAN}} className="wm-geo" />
      <path d={{THREE}} className="wm-3d" />
    </svg>
  );
}}

/** Mark + wordmark lockup. The accessible name lives on the wrapper. */
export function Logo({{ tone = "light", className }}: {{ tone?: Tone; className?: string }}) {{
  return (
    <span className={{`logo logo-${{tone}} ${{className ?? ""}}`}}>
      <Mark tone={{tone}} />
      <Wordmark />
    </span>
  );
}}
'''
open(os.path.join(H, "..", "..", "components", "Logo.tsx"), "w", encoding="utf-8").write(src)
print("ok", len(src))
